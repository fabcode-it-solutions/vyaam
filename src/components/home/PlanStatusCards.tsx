import { memo, useCallback, useMemo } from 'react';
import { ActivityIndicator, Pressable, StyleSheet, View } from 'react-native';

import { Card, ChevronIcon, DumbbellIcon, ForkKnifeIcon, RefreshIcon, Text } from '@/components/ui';
import type { DietPlanForDate, DietPlanMeal } from '@/lib/api/endpoints/dietPlan';
import type { WorkoutDay, WorkoutWeekDay } from '@/lib/api/endpoints/workoutPlan';
import { Radius, Spacing, useTheme } from '@/theme';

// Typical Indian meal-time windows, used only to pick which meal "next up"
// should point at — not an exact schedule, just enough to skip meals whose
// window has passed (e.g. don't suggest breakfast at 4pm just because it's
// still unlogged).
const MEAL_TIME_WINDOWS: { type: DietPlanMeal['type']; startHour: number }[] = [
  { type: 'breakfast', startHour: 0 },
  { type: 'lunch', startHour: 11 },
  { type: 'snack', startHour: 16 },
  { type: 'dinner', startHour: 19 },
];

function currentMealWindowIndex(): number {
  const hour = new Date().getHours();
  let index = 0;
  for (let i = 0; i < MEAL_TIME_WINDOWS.length; i++) {
    if (hour >= MEAL_TIME_WINDOWS[i].startHour) index = i;
  }
  return index;
}

function findNextMeal(plan: DietPlanForDate): DietPlanMeal | null {
  // Only look from the current time-of-day window forward — a still-unlogged
  // breakfast shouldn't outrank an afternoon snack. Meals whose window has
  // already passed are surfaced separately as "missed", not as "next up".
  const currentIndex = currentMealWindowIndex();
  for (let i = currentIndex; i < MEAL_TIME_WINDOWS.length; i++) {
    const pending = plan.meals.find((meal) => meal.type === MEAL_TIME_WINDOWS[i].type && !meal.eaten);
    if (pending) return pending;
  }
  return null;
}

function findMissedMealTypes(plan: DietPlanForDate): DietPlanMeal['type'][] {
  const currentIndex = currentMealWindowIndex();
  return MEAL_TIME_WINDOWS.slice(0, currentIndex)
    .map((window) => window.type)
    .filter((type) => plan.meals.some((meal) => meal.type === type && !meal.eaten));
}

function joinWithAnd(items: string[]): string {
  if (items.length <= 1) return items[0] ?? '';
  if (items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0, -1).join(', ')}, and ${items[items.length - 1]}`;
}

export type DietPlanCardProps = {
  loading: boolean;
  plan: DietPlanForDate | null;
  onView: () => void;
  onGenerate: () => void;
  /** Omit to hide the regenerate affordance entirely (e.g. while its own request is already in flight elsewhere). */
  onRegenerate?: () => void;
  /** Shows a spinner in place of the regenerate icon while a POST /plans/regenerate request is in flight. */
  regenerating?: boolean;
};

/**
 * Customer/Home "your plans" tile — mirrors the today's plan generated by the
 * AI diet intake flow (GET /plans/diet). Full-width row card (icon, title +
 * summary, chevron) — stacked with WorkoutPlanCard rather than side by side.
 * Shows a generate CTA instead of a summary when no plan exists yet. When a
 * plan exists, adds a calorie progress bar and the next unlogged meal so
 * Home doubles as an at-a-glance "what's left today" view, plus a regenerate
 * icon (backend allows one successful regeneration per plan type per rolling
 * 7 days — see assertWeeklyPlanQuota in vyaam-backend) next to the chevron.
 */
export const DietPlanCard = memo(function DietPlanCard({
  loading,
  plan,
  onView,
  onGenerate,
  onRegenerate,
  regenerating,
}: DietPlanCardProps) {
  const { colors } = useTheme();
  const handlePress = useCallback(() => (plan ? onView() : onGenerate()), [plan, onView, onGenerate]);

  const progressPct = plan
    ? Math.min(100, Math.round((plan.caloriesConsumed / plan.dailyCalorieTarget) * 100))
    : 0;
  const nextMeal = useMemo(() => (plan ? findNextMeal(plan) : null), [plan]);
  const missedMealTypes = useMemo(() => (plan ? findMissedMealTypes(plan) : []), [plan]);

  return (
    <Pressable accessibilityRole="button" accessibilityLabel="Diet plan" onPress={handlePress}>
      <Card style={styles.card}>
        <View style={styles.row}>
          <View style={[styles.iconCircle, { backgroundColor: colors.verifiedTint }]}>
            <ForkKnifeIcon size={22} color={colors.verified} />
          </View>
          <View style={styles.textCol}>
            <Text variant="h5">Diet plan</Text>
            {loading ? (
              <ActivityIndicator color={colors.textMuted} style={styles.spinner} />
            ) : plan ? (
              <Text variant="caption" color="textSecondary" numberOfLines={1}>
                {plan.caloriesConsumed.toLocaleString()} / {plan.dailyCalorieTarget.toLocaleString()} kcal
              </Text>
            ) : (
              <Text variant="caption" color="textSecondary" numberOfLines={1}>
                Get a personalized AI diet plan
              </Text>
            )}
          </View>
          <View style={styles.trailing}>
            {!loading && plan && onRegenerate && (
              <RegenerateButton
                accessibilityLabel="Regenerate diet plan"
                pending={!!regenerating}
                onPress={onRegenerate}
              />
            )}
            <Text variant="caption" color="accentDeep" numberOfLines={1}>
              {plan ? 'View' : 'Generate'}
            </Text>
            <ChevronIcon size={14} color={colors.accentDeep} />
          </View>
        </View>

        {!loading && plan && (
          <>
            <View style={[styles.progressTrack, { backgroundColor: colors.border }]}>
              <View style={[styles.progressFill, { width: `${progressPct}%`, backgroundColor: colors.verified }]} />
            </View>
            {missedMealTypes.length > 0 && (
              <Text variant="caption" color="danger" numberOfLines={1}>
                You missed {joinWithAnd(missedMealTypes)} · Tap to mark as eaten
              </Text>
            )}
            {nextMeal ? (
              <Text variant="caption" color="textMuted" numberOfLines={1}>
                Next up: {nextMeal.name}
              </Text>
            ) : missedMealTypes.length === 0 ? (
              <Text variant="caption" color="textMuted" numberOfLines={1}>
                All meals logged for today
              </Text>
            ) : null}
          </>
        )}
      </Card>
    </Pressable>
  );
});

export type WorkoutPlanCardProps = {
  loading: boolean;
  day: WorkoutDay | null;
  /** Tomorrow's entry from GET /plans/workout?weekOf= — omitted while the week fetch is in flight. */
  tomorrow?: WorkoutWeekDay | null;
  onView: () => void;
  onGenerate: () => void;
  /** Omit to hide the regenerate affordance entirely (e.g. while its own request is already in flight elsewhere). */
  onRegenerate?: () => void;
  /** Shows a spinner in place of the regenerate icon while a POST /plans/regenerate request is in flight. */
  regenerating?: boolean;
};

function tomorrowLabel(tomorrow: WorkoutWeekDay): string {
  if (tomorrow.isRestDay) return 'Tomorrow: Rest day';
  const durationSuffix = tomorrow.durationMinutes ? ` · ${tomorrow.durationMinutes} min` : '';
  return `Tomorrow: ${tomorrow.title ?? tomorrow.focusArea ?? 'Workout'}${durationSuffix}`;
}

/**
 * Customer/Home "your plans" tile — today's entry from GET /plans/workout,
 * plus a completed/total count for today's exercises and a peek at
 * tomorrow's session so the card doubles as a "what's next" widget.
 */
export const WorkoutPlanCard = memo(function WorkoutPlanCard({
  loading,
  day,
  tomorrow,
  onView,
  onGenerate,
  onRegenerate,
  regenerating,
}: WorkoutPlanCardProps) {
  const { colors } = useTheme();
  const handlePress = useCallback(() => (day ? onView() : onGenerate()), [day, onView, onGenerate]);

  const totalExercises = day?.exercises.length ?? 0;
  const completedExercises = day?.exercises.filter((exercise) => exercise.completed).length ?? 0;
  const showCompletionCount = !!day && !day.isRestDay && totalExercises > 0;

  const summary = !day
    ? 'Get a personalized AI workout plan'
    : day.isRestDay
      ? 'Rest day today'
      : `${day.title ?? day.focusArea ?? 'Workout'}${day.durationMinutes ? ` · ${day.durationMinutes} min` : ''}` +
        (showCompletionCount ? ` · ${completedExercises}/${totalExercises} done` : '');

  return (
    <Pressable accessibilityRole="button" accessibilityLabel="Workout plan" onPress={handlePress}>
      <Card style={styles.card}>
        <View style={styles.row}>
          <View style={[styles.iconCircle, { backgroundColor: colors.infoTint }]}>
            <DumbbellIcon size={22} color={colors.info} />
          </View>
          <View style={styles.textCol}>
            <Text variant="h5">Workout plan</Text>
            {loading ? (
              <ActivityIndicator color={colors.textMuted} style={styles.spinner} />
            ) : (
              <Text variant="caption" color="textSecondary" numberOfLines={1}>
                {summary}
              </Text>
            )}
          </View>
          <View style={styles.trailing}>
            {!loading && day && onRegenerate && (
              <RegenerateButton
                accessibilityLabel="Regenerate workout plan"
                pending={!!regenerating}
                onPress={onRegenerate}
              />
            )}
            <Text variant="caption" color="accentDeep" numberOfLines={1}>
              {day ? 'View' : 'Generate'}
            </Text>
            <ChevronIcon size={14} color={colors.accentDeep} />
          </View>
        </View>

        {!loading && day && tomorrow && (
          <Text variant="caption" color="textMuted" numberOfLines={1}>
            {tomorrowLabel(tomorrow)}
          </Text>
        )}
      </Card>
    </Pressable>
  );
});

type RegenerateButtonProps = {
  accessibilityLabel: string;
  pending: boolean;
  onPress: () => void;
};

/**
 * Small icon-only tap target nested inside each plan card's outer Pressable
 * (RN's responder system resolves the touch to this inner one, so it doesn't
 * also trigger the card's onView) — kept separate from `onView`/`onGenerate`
 * so tapping it never navigates away before the confirmation Alert in Home
 * resolves.
 */
const RegenerateButton = memo(function RegenerateButton({ accessibilityLabel, pending, onPress }: RegenerateButtonProps) {
  const { colors } = useTheme();
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={accessibilityLabel}
      hitSlop={8}
      disabled={pending}
      onPress={onPress}
      style={styles.regenerateButton}>
      {pending ? (
        <ActivityIndicator size="small" color={colors.textMuted} />
      ) : (
        <RefreshIcon size={16} color={colors.textSecondary} />
      )}
    </Pressable>
  );
});

